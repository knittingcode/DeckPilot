#!/usr/bin/env python3
"""Channel outputs from a verified release input (docs/distribution/README.md,
section 6.4), as dry runs: files to review, never published.

    tools/distribution/generate.py <channel> --input <input.json> --out <dir> [options]

<input.json> is what verify-release-input.sh wrote. Channels:

  homebrew  Cask (Ruby) for the two notarized GitHub DMGs, `auto_updates
            true`: the app keeps its signed self-update (capability matrix,
            section 4). Stable releases are `deckpilot`; pre-releases go to
            `deckpilot@alpha` / `deckpilot@beta` (a real job publishes
            stable only).
  winget    The three WinGet manifests (version, installer, defaultLocale)
            for the GitHub MSI. Pre-releases use the separate identifier
            knittingcode.DeckPilot.Prerelease. --product-code <guid> adds the
            MSI ProductCode (the workflow reads it with msitools).
  apt       An APT repository tree for the `apt` .deb variant (pool/,
            dists/<suite>/main/binary-amd64/Packages, an unsigned
            dists/<suite>/Release). Refuses anything but the apt variant
            (rule R7) and a package whose Version is not the Debian form of
            the release version. InRelease and Release.gpg need the
            repository key and are not written.
  flathub   The Flatpak manifest (packaging/flatpak) with the release's
            tag and commit.
  mas       A build plan for the Mac App Store variant with the draft
            entitlements; nothing is built or signed.
  msstore   The MSIX AppxManifest.xml draft (full trust, startup task for
            the agent) with Partner Center placeholders, and the MSI
            listing's versioned URL.

Every channel also writes summary.json: what was generated, that nothing
was published, and what blocks a real publication.
"""

import argparse
import io
import json
import pathlib
import shutil
import sys
import tarfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import distlib  # noqa: E402
from distlib import Failure  # noqa: E402

PRODUCT = "DeckPilot"
DESCRIPTION = "Stream Deck management"
HOMEPAGE = "https://github.com/knittingcode/deckpilot"
LICENSE = "Apache-2.0"
IDENTIFIER = "io.github.knittingcode.deckpilot"
WINGET_ID = "knittingcode.DeckPilot"
WINGET_MANIFEST_VERSION = "1.10.0"
DEB_PACKAGE = "deck-pilot"  # the Tauri bundler's kebab-case product name


def by_matrix(inputs, matrix_id):
    for artifact in inputs["artifacts"]:
        if artifact.get("matrix_id") == matrix_id:
            return artifact
    raise Failure(f"input.json has no verified artifact of {matrix_id}")


def ruby_string(value):
    return json.dumps(value)


# --- Homebrew -----------------------------------------------------------------


def homebrew(inputs, out, _options):
    arm = by_matrix(inputs, "github-macos-arm64")
    intel = by_matrix(inputs, "github-macos-x64")
    version = inputs["version"]
    for artifact, arch in ((arm, "aarch64"), (intel, "x64")):
        expected = f"{PRODUCT}_{version}_{arch}.dmg"
        if artifact["name"] != expected:
            raise Failure(f"{artifact['name']} is not the DMG name the cask's url builds ({expected})")
    channel = inputs["release_channel"]
    token = "deckpilot" if channel == "stable" else f"deckpilot@{channel}"
    repository = inputs["repository"]
    lines = [
        "# Generated by tools/distribution/generate.py homebrew from the verified",
        f"# release {inputs['tag']} (commit {inputs['commit']}). Dry run: not submitted.",
        f"cask {ruby_string(token)} do",
        '  arch arm: "aarch64", intel: "x64"',
        "",
        f"  version {ruby_string(version)}",
        f"  sha256 arm:   {ruby_string(arm['sha256'])},",
        f"         intel: {ruby_string(intel['sha256'])}",
        "",
        f'  url "https://github.com/{repository}/releases/download/v#{{version}}/{PRODUCT}_#{{version}}_#{{arch}}.dmg",',
        f"      verified: {ruby_string(f'github.com/{repository}/')}",
        f"  name {ruby_string(PRODUCT)}",
        f"  desc {ruby_string(DESCRIPTION)}",
        f"  homepage {ruby_string(HOMEPAGE)}",
        "",
        "  # The app updates itself with its signed updater (GitHub channel).",
        "  auto_updates true",
        '  depends_on macos: ">= :ventura"',
        "",
        f'  app "{PRODUCT}.app"',
        "",
        "  zap trash: [",
        f'    "~/Library/Application Support/{IDENTIFIER}",',
        '    "~/Library/LaunchAgents/DeckPilot Agent.plist",',
        "  ]",
        "end",
    ]
    path = out / f"{token}.rb"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    blockers = ["a GitHub token for a fork of Homebrew/homebrew-cask or for an own tap (not provisioned)"]
    if channel != "stable":
        blockers.insert(0, "pre-release: the distribute-homebrew job publishes stable releases only")
    return [path], blockers


# --- WinGet -------------------------------------------------------------------


def yaml_scalar(value):
    # JSON strings are valid YAML scalars.
    return json.dumps(value)


def winget(inputs, out, options):
    msi = by_matrix(inputs, "github-windows-msi")
    identifier = WINGET_ID if not inputs["prerelease"] else f"{WINGET_ID}.Prerelease"
    version = inputs["version"]
    header = (
        f"# Generated by tools/distribution/generate.py winget from the verified release {inputs['tag']}\n"
        f"# (commit {inputs['commit']}). Dry run: not submitted.\n"
    )
    schema = "https://aka.ms/winget-manifest.{kind}." + WINGET_MANIFEST_VERSION + ".schema.json"

    def manifest(kind, body):
        return header + f"# yaml-language-server: $schema={schema.format(kind=kind)}\n" + body

    version_file = manifest("version", "\n".join([
        f"PackageIdentifier: {identifier}",
        f"PackageVersion: {yaml_scalar(version)}",
        "DefaultLocale: en-US",
        "ManifestType: version",
        f"ManifestVersion: {WINGET_MANIFEST_VERSION}",
        "",
    ]))
    installer_lines = [
        f"PackageIdentifier: {identifier}",
        f"PackageVersion: {yaml_scalar(version)}",
        "InstallerType: wix",
        "Scope: machine",
        "UpgradeBehavior: install",
        "Installers:",
        "  - Architecture: x64",
        f"    InstallerUrl: {yaml_scalar(msi['url'])}",
        f"    InstallerSha256: {msi['sha256'].upper()}",
    ]
    if options.product_code:
        installer_lines.append(f"    ProductCode: {yaml_scalar(options.product_code)}")
    installer_lines += ["ManifestType: installer", f"ManifestVersion: {WINGET_MANIFEST_VERSION}", ""]
    installer_file = manifest("installer", "\n".join(installer_lines))
    locale_file = manifest("defaultLocale", "\n".join([
        f"PackageIdentifier: {identifier}",
        f"PackageVersion: {yaml_scalar(version)}",
        "PackageLocale: en-US",
        "Publisher: knittingcode",
        f"PackageName: {PRODUCT}" + (" (Prerelease)" if inputs["prerelease"] else ""),
        f"PackageUrl: {HOMEPAGE}",
        f"License: {LICENSE}",
        f"ShortDescription: {DESCRIPTION}",
        f"ReleaseNotesUrl: https://github.com/{inputs['repository']}/releases/tag/{inputs['tag']}",
        "ManifestType: defaultLocale",
        f"ManifestVersion: {WINGET_MANIFEST_VERSION}",
        "",
    ]))
    # The layout of microsoft/winget-pkgs: manifests/<first letter>/<publisher>/<name>/<version>/.
    directory = out / "manifests" / identifier[0].lower() / pathlib.Path(*identifier.split(".")) / version
    directory.mkdir(parents=True, exist_ok=True)
    paths = []
    for suffix, text in (("", version_file), (".installer", installer_file), (".locale.en-US", locale_file)):
        path = directory / f"{identifier}{suffix}.yaml"
        path.write_text(text, encoding="utf-8")
        paths.append(path)
    blockers = [
        "a GitHub token for a fork of microsoft/winget-pkgs (not provisioned)",
        "Windows Authenticode signing is not provisioned (audit G11); advised against SmartScreen and scanner false positives",
    ]
    if not options.product_code:
        blockers.append("ProductCode not given (read it from the MSI with msitools: msiinfo export <msi> Property)")
    return paths, blockers


# --- APT ----------------------------------------------------------------------


def ar_members(data):
    if not data.startswith(b"!<arch>\n"):
        raise Failure("not a Debian package (no ar header)")
    offset, members = 8, {}
    while offset + 60 <= len(data):
        header = data[offset:offset + 60]
        name = header[:16].decode("ascii").strip().rstrip("/")
        size = int(header[48:58].decode("ascii").strip())
        offset += 60
        members[name] = data[offset:offset + size]
        offset += size + (size % 2)
    return members


def deb_control(path):
    members = ar_members(pathlib.Path(path).read_bytes())
    for name, member in members.items():
        if name.startswith("control.tar"):
            if name.endswith(".zst"):
                raise Failure(f"{path}: control.tar.zst is not supported by this dry run")
            with tarfile.open(fileobj=io.BytesIO(member), mode="r:*") as archive:
                for entry in archive.getmembers():
                    if entry.name.lstrip("./") == "control":
                        return archive.extractfile(entry).read().decode("utf-8")
    raise Failure(f"{path}: no control file")


def control_fields(text):
    fields, key = {}, None
    for line in text.splitlines():
        if line.startswith((" ", "\t")) and key:
            fields[key] += "\n" + line
        elif ":" in line:
            key, _, value = line.partition(":")
            fields[key.strip()] = value.strip()
    return fields


def apt(inputs, out, _options):
    deb = by_matrix(inputs, "apt-deb")
    if deb.get("distribution_channel") != "apt" or deb.get("package_format") != "deb":
        raise Failure(f"{deb['name']} is not the apt .deb variant (rule R7)")
    text = deb_control(deb["path"])
    fields = control_fields(text)
    expected = distlib.debian_version(inputs["version"])
    if fields.get("Version") != expected:
        raise Failure(
            f"{deb['name']} has Version {fields.get('Version')!r}; the APT variant must carry the Debian form "
            f"{expected!r} so that dpkg orders pre-releases before the release"
        )
    if fields.get("Package") != DEB_PACKAGE:
        raise Failure(f"{deb['name']} is the package {fields.get('Package')!r}, expected {DEB_PACKAGE}")
    suite = "stable" if not inputs["prerelease"] else "prerelease"
    arch = fields.get("Architecture", "amd64")
    pool = pathlib.Path("pool") / "main" / DEB_PACKAGE[0] / DEB_PACKAGE / deb["name"]
    (out / pool).parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(deb["path"], out / pool)
    stanza = text.rstrip("\n") + "\n" + "\n".join([
        f"Filename: {pool.as_posix()}",
        f"Size: {deb['size']}",
        f"SHA256: {deb['sha256']}",
    ]) + "\n"
    binary = pathlib.Path("dists") / suite / "main" / f"binary-{arch}"
    (out / binary).mkdir(parents=True, exist_ok=True)
    packages = out / binary / "Packages"
    packages.write_text(stanza, encoding="utf-8")
    # Only the uncompressed index: apt reads it, and its bytes do not depend
    # on a compressor's version.
    index = [f" {distlib.sha256_file(packages)} {packages.stat().st_size} main/binary-{arch}/Packages"]
    release = out / "dists" / suite / "Release"
    release.write_text("\n".join([
        "Origin: DeckPilot",
        "Label: DeckPilot",
        f"Suite: {suite}",
        f"Codename: {suite}",
        f"Architectures: {arch}",
        "Components: main",
        "Description: DeckPilot APT repository (dry run, unsigned)",
        "SHA256:",
        *index,
        "",
    ]), encoding="utf-8")
    blockers = [
        "the release workflow does not build the apt variant yet (targets.toml apt-deb is planned)",
        "repository GPG key for InRelease and Release.gpg (not provisioned)",
        "a repository host and its deploy credential (not provisioned)",
    ]
    return [out / pool, packages, release], blockers


# --- Flathub ------------------------------------------------------------------


def flathub(inputs, out, options):
    source = pathlib.Path(options.manifest)
    text = source.read_text(encoding="utf-8")
    for placeholder in ("@TAG@", "@COMMIT@"):
        if placeholder not in text:
            raise Failure(f"{source} has no {placeholder} placeholder")
    text = text.replace("@TAG@", inputs["tag"]).replace("@COMMIT@", inputs["commit"])
    path = out / source.name
    path.write_text(text, encoding="utf-8")
    blockers = [
        "the manifest has never been built (flatpak-builder was not available; packaging/flatpak/README.md)",
        "cargo-sources.json and node-sources.json are not generated by this dry run",
        "write access to flathub/io.github.knittingcode.deckpilot and app ID verification (not provisioned)",
    ]
    return [path], blockers


# --- Mac App Store ------------------------------------------------------------


def mas(inputs, out, _options):
    templates = HERE / "templates" / "mas"
    paths = []
    for name in ("app.entitlements", "agent.entitlements"):
        shutil.copyfile(templates / name, out / name)
        paths.append(out / name)
    plan = {
        "commit": inputs["commit"],
        "tag": inputs["tag"],
        "build": {
            "env": {"DECKPILOT_DISTRIBUTION_CHANNEL": "mac_app_store", "DECKPILOT_PACKAGE_FORMAT": "mas_pkg"},
            "cargo_features": "--no-default-features (no self-update)",
            "updater_pubkey": None,
            "agent": "Contents/Library/LoginItems/DeckPilot Agent.app (bundle id io.github.knittingcode.deckpilot.agent), registered with SMAppService",
            "plugin_host": "not shipped",
            "signing": "Apple Distribution; the .pkg with Mac Installer Distribution",
            "upload": "App Store Connect, never submitted for review by the job",
        },
    }
    plan_path = out / "plan.json"
    distlib.write_json(plan_path, plan)
    paths.append(plan_path)
    blockers = [
        "a Stream Deck has not been opened from the App Sandbox (experiments/distribution/macos-sandbox-hid: built-in HID devices only)",
        "user-installed plugin code (App Review Guidelines 2.4.5(iv), 2.5.2, 4.7): policy risk, plugins off",
        "the plugin host's own Seatbelt profile is refused inside the App Sandbox (experiments/distribution/macos-sandbox-plugin-host)",
        "the agent as an SMAppService login item app bundle is not built",
        "Apple Distribution and Mac Installer Distribution certificates, provisioning profiles, an App Store Connect app record and API key (not provisioned)",
    ]
    return paths, blockers


# --- Microsoft Store ----------------------------------------------------------


def msix_version(version):
    """MSIX versions are four numbers and the Store reserves the fourth (it
    must be 0). Stable X.Y.Z is X.Y.Z.0; a pre-release has no distinct
    representation yet, so the draft uses X.Y.Z.0 and says so."""
    major, minor, patch, kind, _ = distlib.parse_version(version)
    return f"{major}.{minor}.{patch}.0", kind is not None


def msstore(inputs, out, _options):
    msi = by_matrix(inputs, "github-windows-msi")
    package_version, ambiguous = msix_version(inputs["version"])
    template = (HERE / "templates" / "msix" / "AppxManifest.xml").read_text(encoding="utf-8")
    manifest = template.replace("@VERSION@", package_version)
    manifest_path = out / "AppxManifest.xml"
    manifest_path.write_text(manifest, encoding="utf-8")
    listing = {
        "msi_listing": {
            "package_url": msi["url"],
            "sha256": msi["sha256"],
            "installer_parameters": "/quiet /norestart (Windows Installer, silent)",
            "note": "the MSI/EXE listing is the github channel; the app keeps its signed self-update",
        },
        "msix": {"version": package_version, "built": False},
    }
    listing_path = out / "listing.json"
    distlib.write_json(listing_path, listing)
    blockers = [
        "Authenticode signing from a Microsoft Trusted Root Program CA is required for the MSI listing (not provisioned)",
        "a Microsoft Partner Center account, a reserved name, its publisher identity and API credentials (not provisioned)",
        "hidapi inside an MSIX package has not been tested (distribute.yml experiment-msix-hid, manual)",
        "the plugin host's AppContainer child from a packaged full-trust process is untested",
    ]
    if ambiguous:
        blockers.insert(0, f"pre-release {inputs['version']}: MSIX has no distinct version for it ({package_version} is the release's)")
    return [manifest_path, listing_path], blockers


GENERATORS = {
    "homebrew": homebrew,
    "winget": winget,
    "apt": apt,
    "flathub": flathub,
    "mas": mas,
    "msstore": msstore,
}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("channel", choices=sorted(GENERATORS))
    parser.add_argument("--input", required=True, help="input.json from verify-release-input.sh")
    parser.add_argument("--out", required=True, help="output directory (created)")
    parser.add_argument("--product-code", help="winget: the MSI ProductCode")
    parser.add_argument(
        "--manifest",
        default=str(ROOT / "packaging" / "flatpak" / "io.github.knittingcode.deckpilot.yml"),
        help="flathub: the manifest draft",
    )
    options = parser.parse_args()
    out = pathlib.Path(options.out)
    out.mkdir(parents=True, exist_ok=True)
    try:
        inputs = distlib.load_json(options.input)
        if inputs.get("channel") not in (None, options.channel):
            raise Failure(f"{options.input} was verified for {inputs.get('channel')!r}, not {options.channel}")
        paths, blockers = GENERATORS[options.channel](inputs, out, options)
    except Failure as failure:
        print(f"::error::{options.channel}: {failure}")
        return 1
    summary = {
        "channel": options.channel,
        "tag": inputs["tag"],
        "commit": inputs["commit"],
        "dry_run": True,
        "published": False,
        "outputs": sorted(str(p.relative_to(out)) for p in paths),
        "blockers": blockers,
    }
    distlib.write_json(out / "summary.json", summary)
    for path in summary["outputs"]:
        print(f"{options.channel}: generated {path}")
    print(f"{options.channel}: dry run, nothing published; {len(blockers)} blocker(s) in summary.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
